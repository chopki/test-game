import { chromium } from '@playwright/test';
const [,, out, query = '', zoom, evalStr] = process.argv;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader'] });
const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`http://localhost:5173/?${query}`, { waitUntil: 'commit', timeout: 600000 });
await p.waitForFunction(() => window.game?.world && window.game.renderer.renderer.info.render.frame > 5, null, { timeout: 600000 });
await p.evaluate(() => window.game.togglePause());
if (evalStr) console.log(await p.evaluate((s) => eval(s), evalStr));
if (zoom) await p.evaluate(([z, x, y]) => { const r = window.game.renderer; const v = r.toScene(x, 0, y, new r.camera.position.constructor(), true); const d = r.camera.position.clone().sub(r.controls.target); r.controls.target.copy(v); r.camera.position.copy(v).add(d); r.camera.zoom = z; r.camera.updateProjectionMatrix(); r.controls.update(); }, zoom.split(',').map(Number));
await p.waitForTimeout(1500);
await p.screenshot({ path: out });
console.log(errs);
await b.close();
